export function t(lang, path, vars = {}) {
  const parts = path.split('.');
  let node = translations[lang];
  for (const p of parts) {
    node = node?.[p];
  }
  if (typeof node !== 'string') return path;
  return node.replace(/\{(\w+)\}/g, (_, key) => (vars[key] !== undefined ? vars[key] : `{${key}}`));
}
